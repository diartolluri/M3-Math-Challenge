% main_Q1.m
% Rule-Based Accounting Model with Empirical Equivalence
% Calculates disposable income for demonstration personas
%
% This script:
% 1. Loads tax rates and essential costs data
% 2. Defines 8 demonstration personas
% 3. Processes each persona to calculate disposable income
% 4. Prints formatted results table

%% Clear workspace and add path
clear; clc;

%% 1. Load data files
% Load essential costs data
try
    cost_data = readtable('essential_costs.csv', 'TextType', 'string');
catch
    error('Unable to read essential_costs.csv. Ensure the file exists in the workspace.');
end

%% 2. Define 8 demonstration personas
personas(1) = struct('Description', 'Young Single', ...
                       'Country', 'US', ...
                       'Region', 'TX', ...
                       'GrossSalary', 35000, ...
                       'Age', 24, ...
                       'Adults', 1, ...
                       'Children', 0);

personas(2) = struct('Description', 'Young Single', ...
                       'Country', 'US', ...
                       'Region', 'CA', ...
                       'GrossSalary', 35000, ...
                       'Age', 24, ...
                       'Adults', 1, ...
                       'Children', 0);

personas(3) = struct('Description', 'Mid-Career Single', ...
                       'Country', 'US', ...
                       'Region', 'NY', ...
                       'GrossSalary', 120000, ...
                       'Age', 40, ...
                       'Adults', 1, ...
                       'Children', 0);

personas(4) = struct('Description', 'Mid-Career Family', ...
                       'Country', 'US', ...
                       'Region', 'NY', ...
                       'GrossSalary', 120000, ...
                       'Age', 40, ...
                       'Adults', 2, ...
                       'Children', 2);

personas(5) = struct('Description', 'Pre-Retiree', ...
                       'Country', 'US', ...
                       'Region', 'FL', ...
                       'GrossSalary', 65000, ...
                       'Age', 62, ...
                       'Adults', 2, ...
                       'Children', 0);

personas(6) = struct('Description', 'Young Single', ...
                       'Country', 'UK', ...
                       'Region', 'England', ...
                       'GrossSalary', 35000, ...
                       'Age', 28, ...
                       'Adults', 1, ...
                       'Children', 0);

personas(7) = struct('Description', 'Mid-Career Family', ...
                       'Country', 'UK', ...
                       'Region', 'Scotland', ...
                       'GrossSalary', 65000, ...
                       'Age', 45, ...
                       'Adults', 2, ...
                       'Children', 2);

personas(8) = struct('Description', 'Pensioner', ...
                       'Country', 'UK', ...
                       'Region', 'Wales', ...
                       'GrossSalary', 25000, ...
                       'Age', 72, ...
                       'Adults', 1, ...
                       'Children', 0);

%% 3. Process each persona in a loop
n = numel(personas);

% Preallocate arrays for results
net_income = zeros(n, 1);
household_essentials = zeros(n, 1);
individual_essentials = zeros(n, 1);
disposable_income = zeros(n, 1);

for i = 1:n
    persona = personas(i);
    
    % Call calculate_taxes to get net_income
    net_income(i) = calculate_taxes(persona);
    
    % Call calculate_essentials to get household_essentials
    household_essentials(i) = calculate_essentials(persona, cost_data);
    
    % Call apply_oecd_scale to get individual_essentials
    individual_essentials(i) = apply_oecd_scale(household_essentials(i), persona.Adults, persona.Children);
    
    % Calculate disposable income (max of net_income - individual_essentials or 0)
    disposable_income(i) = max(net_income(i) - individual_essentials(i), 0);
end

%% 4. Print formatted table
% Create formatted output table
fprintf('\n');
fprintf('========================================================================================================\n');
fprintf('                     RULE-BASED ACCOUNTING MODEL WITH EMPIRICAL EQUIVALENCE\n');
fprintf('                                   Disposable Income Results\n');
fprintf('========================================================================================================\n');
fprintf('\n');
fprintf('%-20s %-8s %-12s %12s %6s %7s %8s %12s %18s %18s\n', ...
    'Description', 'Country', 'Region', 'Gross Salary', 'Age', 'Adults', 'Children', 'Net Income', 'Ind. Essentials', 'Disposable Income');
fprintf('%s\n', repmat('-', 1, 130));

for i = 1:n
    p = personas(i);
    currency = '';
    if strcmp(p.Country, 'US')
        currency = '$';
    else
        currency = '£';
    end
    
    fprintf('%-20s %-8s %-12s %s%11.2f %6d %7d %8d %s%11.2f %s%17.2f %s%17.2f\n', ...
        p.Description, p.Country, p.Region, currency, p.GrossSalary, p.Age, p.Adults, p.Children, ...
        currency, net_income(i), currency, individual_essentials(i), currency, disposable_income(i));
end

fprintf('%s\n', repmat('-', 1, 130));
fprintf('\n');
fprintf('Notes:\n');
fprintf('  - Net Income = Gross Salary - Taxes (Federal/State/National Insurance)\n');
fprintf('  - Individual Essentials = Household Essentials / OECD Equivalence Scale\n');
fprintf('  - Disposable Income = max(Net Income - Individual Essentials, 0)\n');
fprintf('  - OECD Scale: EQ = 1.0 + 0.5*(Adults-1) + 0.3*Children\n');
fprintf('\n');

end
